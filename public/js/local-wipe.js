/**
 * Забыть всё местное при выходе из аккаунта.
 *
 * Правило одно, а выходов из аккаунта два — из веб-версии и с прежнего экрана
 * настроек, — и раньше каждый убирал своё. Прежний экран звал только
 * `api.logout()`, поэтому в хранилище оставались последняя копия дня, очередь
 * правок, имя хозяина и дневник. Дальше index.html видел сохранённые настройки
 * и уводил следующего человека прямо в приложение, где до первого ответа
 * сервера были видны дни и имя предыдущего.
 *
 * Здесь только хранилище: состояние в памяти и очередь убирает тот, у кого они
 * есть (см. web/store.js).
 */

const ПРЕФИКСЫ = ['newday.local.', 'newday.outbox', 'newday.diag'];
const КЛЮЧИ = ['newday.owner'];

/** @returns {number} сколько ключей убрано */
export function wipeLocalKeys() {
  try {
    // перебираем через length/key, а не Object.keys: так хранилище
    // перечисляется по своим правилам, а не по случайным полям объекта
    const ключи = [];
    for (let i = 0; i < localStorage.length; i++) {
      const k = localStorage.key(i);
      if (!k) continue;
      if (КЛЮЧИ.includes(k) || ПРЕФИКСЫ.some(p => k.startsWith(p))) ключи.push(k);
    }
    for (const k of ключи) localStorage.removeItem(k);
    return ключи.length;
  } catch {
    return 0;   // хранилища нет — и забывать нечего
  }
}
