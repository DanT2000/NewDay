/**
 * Очередь правок, которые ещё не уехали на сервер.
 *
 * Приложение больше не ждёт сеть: правка применяется на устройстве и
 * ложится сюда, а отсюда уезжает сама — когда получится. Поэтому у очереди
 * две обязанности, и обе важнее скорости: ничего не потерять и ничего не
 * задвоить.
 *
 * Хранится в localStorage: правка обязана пережить и закрытие приложения, и
 * перезагрузку страницы. Читается синхронно, потому что счётчик в шапке
 * нужен до первой отрисовки.
 */

import { временный } from './web/ops.js';

const КЛЮЧ = 'newday.outbox.v1';
const КЛЮЧ_БЕДА = 'newday.outbox.bad.v1';
const КЛЮЧ_ЗАМОК = 'newday.outbox.lock';

/*
 * Дольше этого одна вкладка очередь не держит: вдруг её усыпили посреди
 * прогона. Срок заведомо больше предела ожидания запроса (api.js, 20 с):
 * при равных сроках аренда истекала ровно во время долгого запроса, вторая
 * вкладка считала очередь ничьей и отправляла ту же правку второй раз — в
 * дне появлялись две одинаковые строки.
 */
const АРЕНДА_МС = 45000;
/** Больше пятисот неотправленных — это не «нет связи», это беда посерьёзнее. */
const ПРЕДЕЛ = 500;
/** Сбой сервера бывает мгновенным; три попытки отделяют его от настоящей поломки. */
const ПОПЫТОК = 3;
const ПАУЗЫ = [2000, 4000, 8000, 15000, 30000, 60000];

const вкладка = `t${Math.random().toString(36).slice(2, 7)}`;
let счётчик = 0;
let отправитель = null;
let автоповтор = true;
/** Идущий прогон: второй вызов не начинает свой, а дожидается этого. */
let текущий = null;
/** Обещанный прогон следом за идущим: чтобы правка не ждала случайного повода. */
let дожать = null;
let таймер = null;
let пауза = 0;
const слушатели = new Set();

// ── Хранилище ────────────────────────────────────────────────

/*
 * Любое обращение к localStorage обёрнуто: в приватном режиме оно бросает,
 * а очередь, падающая от режима браузера, хуже очереди без памяти.
 */
function прочитать(ключ) {
  try {
    const raw = globalThis.localStorage?.getItem(ключ);
    const val = raw ? JSON.parse(raw) : null;
    return Array.isArray(val?.ops) ? val.ops : [];
  } catch { return []; }
}

/** Возвращает `false`, если запись не удалась: переполнение или приватный режим. */
function записать(ключ, ops) {
  try {
    globalThis.localStorage?.setItem(ключ, JSON.stringify({ v: 1, ops }));
    return true;
  } catch { return false; }
}

const очередь = () => прочитать(КЛЮЧ);
const беды = () => прочитать(КЛЮЧ_БЕДА);

// ── Наружу ───────────────────────────────────────────────────

export function настроить(opts = {}) {
  if (opts.отправитель) отправитель = opts.отправитель;
  if (opts.автоповтор !== undefined) автоповтор = opts.автоповтор;
}

export const список = () => очередь();
export const ожидает = () => очередь().length;
export const конфликты = () => беды();

export function подписаться(fn) {
  слушатели.add(fn);
  return () => слушатели.delete(fn);
}

function сообщить(весть) {
  for (const fn of слушатели) {
    try { fn(весть); } catch { /* слушатель не должен ронять очередь */ }
  }
}

/** Временный id новой строки. Вкладка в имени — чтобы две не совпали. */
export const новыйId = () => `tmp-${вкладка}-${++счётчик}`;

export function добавить(правка) {
  const ops = очередь();
  if (ops.length >= ПРЕДЕЛ) {
    throw new Error('Накопилось слишком много несохранённых правок — нужна связь с сервером');
  }
  const оп = {
    id: `op-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`,
    at: Date.now(),
    попытки: 0,
    ошибка: null,
    ...правка,
  };
  /*
   * Не сохранилось — значит правки нет. Раньше отказ хранилища проглатывался
   * молча: на экране правка есть, в очереди её нет, и при перезагрузке она
   * исчезала бесследно. Лучше честный отказ, который человек увидит.
   */
  if (!записать(КЛЮЧ, [...ops, оп])) {
    throw new Error('Не удалось сохранить правку на устройстве: в браузере кончилось место');
  }
  сообщить({ вид: 'счёт' });
  if (автоповтор) отправить();
  return оп;
}

export function забыть(id) {
  записать(КЛЮЧ_БЕДА, беды().filter(о => о.id !== id));
  сообщить({ вид: 'счёт' });
}

export function повторить(id) {
  const оп = беды().find(о => о.id === id);
  if (!оп) return;
  записать(КЛЮЧ_БЕДА, беды().filter(о => о.id !== id));
  записать(КЛЮЧ, [...очередь(), { ...оп, попытки: 0, ошибка: null }]);
  сообщить({ вид: 'счёт' });
  if (автоповтор) отправить();
}

export function очистить() {
  записать(КЛЮЧ, []);
  записать(КЛЮЧ_БЕДА, []);
  сообщить({ вид: 'счёт' });
}

// ── Замок между вкладками ────────────────────────────────────

/*
 * Очередь общая на все вкладки, а отправлять её должна одна. Аренда с
 * временем жизни, а не «занято/свободно»: вкладку могли усыпить или закрыть
 * посреди прогона, и вечный замок остановил бы синхронизацию навсегда.
 */
function взятьЗамок() {
  try {
    const raw = globalThis.localStorage?.getItem(КЛЮЧ_ЗАМОК);
    const замок = raw ? JSON.parse(raw) : null;
    if (замок && замок.tab !== вкладка && замок.until > Date.now()) return false;
    globalThis.localStorage?.setItem(КЛЮЧ_ЗАМОК,
      JSON.stringify({ tab: вкладка, until: Date.now() + АРЕНДА_МС }));
    return true;
  } catch { return true; }   // нет хранилища — значит, вкладка и так одна
}

function отдатьЗамок() {
  try {
    const raw = globalThis.localStorage?.getItem(КЛЮЧ_ЗАМОК);
    if (raw && JSON.parse(raw).tab === вкладка) globalThis.localStorage.removeItem(КЛЮЧ_ЗАМОК);
  } catch { /* уже некому отдавать */ }
}

// ── Отправка ─────────────────────────────────────────────────

/** Снять правку с очереди. `false` — записать не удалось, правка ещё там. */
function снять(id) {
  return записать(КЛЮЧ, очередь().filter(о => о.id !== id));
}

/*
 * Список «не доехали» тоже ограничен — но щедро.
 *
 * Предел нужен, чтобы сервер, отвергающий всё подряд, не забил хранилище:
 * когда место кончится, перестанет сохраняться сама очередь. Но выбрасывая
 * отсюда запись, мы выбрасываем не уведомление, а единственную копию
 * правки — вернуть её человеку будет нечем. Поэтому предел тот же, что у
 * очереди: до него доходят только в совсем безнадёжном случае.
 */
const БЕД_ХРАНИМ = ПРЕДЕЛ;

/** Дописать правку в «не сохранилось». `false` — записать не удалось. */
function вБеду(оп, ошибка) {
  const список = [...беды(), { ...оп, ошибка: ошибка?.message || 'Не сохранилось' }];
  if (!записать(КЛЮЧ_БЕДА, список.slice(-БЕД_ХРАНИМ))) return false;
  сообщить({ вид: 'конфликт', оп });
  return true;
}

/*
 * Переложить правку из очереди в «не сохранилось» — целиком или никак.
 *
 * Оба списка лежат в одном хранилище, и когда в нём кончается место,
 * половина перекладывания означала потерю: список бед не записался, а с
 * очереди правка снята — и её не стало нигде, молча. Обратный порядок не
 * лучше: очередь не записалась, правка осталась первой, и прогон отправлял
 * её по кругу — телефон грелся, сервер получал один и тот же отказ, счётчик
 * не двигался.
 *
 * Поэтому сначала копия, потом снятие; не удалось — прогон останавливается,
 * и человек узнаёт, что на устройстве нет места.
 */
function отложить(оп, ошибка) {
  if (!вБеду(оп, ошибка) || !снять(оп.id)) {
    сообщить({ вид: 'нетМеста', оп });
    return false;
  }
  return true;
}

/**
 * Строку не создали — значит менять в ней нечего.
 *
 * Зависимые правки уезжали следом с временным номером, получали свой отказ
 * и ложились в список рядом: из одной беды человек видел три, и каждая
 * обречена. Убираем их вместе с создателем — молча, потому что показывать
 * три сообщения об одном событии хуже, чем одно.
 */
function убратьЗависимые(цель) {
  if (!временный(цель)) return;
  const свои = о => String(о.цель) === String(цель)
    || Object.values(о.данные?.поля ?? {}).some(v => String(v) === String(цель));
  записать(КЛЮЧ, очередь().filter(о => !свои(о)));
}

/**
 * Настоящий id вместо временного — и в очереди, и у того, кто слушает.
 *
 * Меняем не только адрес правки, но и ссылки внутри полей: приём пищи
 * ссылается на свой блок расписания полем `scheduleItemId`, и без этого на
 * сервер уезжало бы «tmp-…» вместо номера — связь между записью и блоком
 * терялась молча.
 */
function подставить(было, стало) {
  const один = знач => (String(знач) === String(было) ? стало : знач);
  записать(КЛЮЧ, очередь().map(о => {
    const поля = о.данные?.поля;
    if (!поля) return String(о.цель) === String(было) ? { ...о, цель: стало } : о;
    return {
      ...о,
      цель: один(о.цель),
      данные: { ...о.данные, поля: Object.fromEntries(
        Object.entries(поля).map(([k, знач]) => [k, один(знач)])) },
    };
  }));
  сообщить({ вид: 'подстановка', было, стало });
}

function позже() {
  if (!автоповтор) return;
  clearTimeout(таймер);
  const мс = ПАУЗЫ[Math.min(пауза, ПАУЗЫ.length - 1)];
  пауза += 1;
  таймер = setTimeout(() => отправить(), мс);
  таймер?.unref?.();
}

/**
 * Прогнать очередь. Пока прогон идёт, повторный вызов возвращает его же:
 * тот, кто ждёт отправки, обязан дождаться настоящего конца, а не второго
 * пустого обещания.
 */
export function отправить() {
  /*
   * Пока прогон идёт, он сам подхватит всё, что добавили: очередь он
   * перечитывает на каждом шаге. Но прогон мог уже выйти — например, ни с
   * чем, на пустой очереди — и ещё не успеть убрать себя. Правка, сделанная
   * в этот миг, раньше получала в ответ мертвеца и ждала случайного повода:
   * события «связь появилась», возврата в приложение или следующего
   * нажатия. Поэтому дожидаемся конца и прогоняем ещё раз — один, чтобы без
   * связи не крутиться вхолостую.
   */
  if (текущий) {
    дожать = дожать ?? текущий.then(() => { дожать = null; return запустить(); });
    return дожать;
  }
  return запустить();
}

function запустить() {
  /*
   * Прогон не имеет права отклониться.
   *
   * Следующий прогон цепляется к этому обещанию (`дожать`), и однажды
   * отклонённое оно осталось бы отклонённым навсегда: `дожать = null` не
   * выполнилось бы, и каждый следующий `отправить()` возвращал бы этот труп —
   * ни одна правка больше не уехала бы до перезагрузки страницы. Внутри
   * прогона всё обёрнуто, но полагаться на это нельзя: цена ошибки — вся
   * очередь целиком.
   */
  текущий = прогон()
    .catch(e => { console.warn('[newday] прогон очереди сорвался:', e?.message || e); })
    .finally(() => { текущий = null; });
  return текущий;
}

async function прогон() {
  if (!отправитель) return;
  if (!очередь().length) { пауза = 0; return; }
  // очередь у другой вкладки — вернёмся сами, а не будем ждать случайного
  // повода: та вкладка могла уснуть посреди прогона
  if (!взятьЗамок()) { позже(); return; }
  try {
    for (;;) {
      // перечитываем каждый раз: соседняя вкладка могла что-то добавить
      const оп = очередь()[0];
      if (!оп) { пауза = 0; break; }
      взятьЗамок();                     // продлеваем аренду на длинной очереди
      let ответ;
      try {
        ответ = await отправитель(оп);
      } catch (e) {
        /*
         * Разбираем отказ по тому, что сервер сказал, а не по тому, чего
         * не сказал. Раньше «нет статуса» означало «нет связи» — и обычное
         * исключение (например, правка незнакомого вида из вкладки со
         * старой версией) вставляло очередь намертво: она стояла вечно, ни
         * одна правка не уезжала и в «не сохранилось» не попадала.
         */
        const сетевая = e?.code === 'NETWORK' || e?.code === 'TIMEOUT' || e?.status === 0
          // портал гостиничного вайфая отвечает своей страницей вместо JSON:
          // сервер правки не видел, значит терять их нельзя
          || e?.code === 'BAD_RESPONSE';
        const код = Number.isInteger(e?.status) ? e.status : null;
        // связи нет — стоим целиком: порядок правок дороже скорости
        if (сетевая) {
          /*
           * И говорим об этом наружу. Экран узнавал об отсутствии связи только
           * потому, что после каждой правки перечитывал день и получал отказ;
           * когда лишний запрос убрали, признак пропал вместе с ним. А знает
           * об этом именно очередь: `navigator.onLine` в «вайфае без
           * интернета» говорит «связь есть».
           */
          сообщить({ вид: 'нетСвязи', оп });
          позже();
          break;
        }
        // вход разберёт api.js; очередь ждёт, а не теряет
        if (код === 401) break;
        // удалять то, чего нет, не нужно: цель достигнута
        if (код === 404 && оп.вид === 'строка.удалить') {
          if (!снять(оп.id)) { сообщить({ вид: 'нетМеста', оп }); break; }
          continue;
        }
        if (код >= 500) {
          const попытки = (оп.попытки ?? 0) + 1;
          if (попытки < ПОПЫТОК) {
            записать(КЛЮЧ, очередь()
              .map(о => (о.id === оп.id ? { ...о, попытки, ошибка: e?.message ?? null } : о)));
            позже();
            break;
          }
          if (!отложить({ ...оп, попытки }, e)) break;
          continue;
        }
        // 4xx: сервер отказал по существу
        if (!отложить(оп, e)) break;
        if (оп.вид === 'строка.создать') убратьЗависимые(оп.цель);
        continue;
      }
      /*
       * Правка уехала — снимаем. Если снять не удалось (место кончилось),
       * останавливаемся: иначе она уедет ещё раз, и ещё, без конца.
       */
      if (!снять(оп.id)) { сообщить({ вид: 'нетМеста', оп }); break; }
      пауза = 0;
      if (оп.вид === 'строка.создать' && временный(оп.цель) && ответ?.id) подставить(оп.цель, ответ.id);
      сообщить({ вид: 'уехала', оп, ответ });
    }
  } finally {
    отдатьЗамок();
    сообщить({ вид: 'счёт' });
  }
}
