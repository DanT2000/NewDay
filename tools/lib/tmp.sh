# Временные файлы эмуляторных прогонов — рядом с проектом, с уборкой на выходе.
#
# Подключать так, из любого скрипта в tools/:
#   . "$(dirname "$0")/lib/tmp.sh"
#   FILE=$(nd_tmpfile newday-ui)
#
# Зачем. `mktemp -t` кладёт файл в системный %TEMP% на диске C, а прогоны его не
# убирали: накопилось 121 файл — дампы uiautomator, журналы матрицы, отчёты.
# Двенадцать мегабайт против тридцати пяти гигабайт от профилей браузера, но
# болезнь та же, и лечится там же — в .tmp рядом с проектом.
#
# Почему каталог на прогон, а не список файлов. Список не работает: файл
# создаётся через `F=$(nd_tmpfile …)`, то есть в подоболочке, и любая запись в
# переменную или массив до родителя не доходит — уборке на выходе оставалось
# пустое место. Каталог создаётся один раз при подключении, в самом скрипте, и
# сносится целиком: одна строка, ничего не забудется, и никакой прогон не
# заденет файлы соседнего.

ND_TMP_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/.tmp"
mkdir -p "$ND_TMP_ROOT"
ND_TMP_RUN="$(mktemp -d "$ND_TMP_ROOT/run-XXXXXX")"

# nd_tmpfile [префикс] — создать временный файл и напечатать путь к нему
nd_tmpfile() { mktemp "$ND_TMP_RUN/${1:-newday}-XXXXXX"; }

# nd_tmpdir [префикс] — то же для каталога
nd_tmpdir() { mktemp -d "$ND_TMP_RUN/${1:-newday}-XXXXXX"; }

# Уборка молчит, когда всё убралось, и говорит вслух, когда нет: пустой
# «ну и ладно» — то, из-за чего утечка жила незамеченной.
nd_tmp_cleanup() {
  [ -n "${ND_TMP_RUN:-}" ] || return 0
  rm -rf "$ND_TMP_RUN" 2>/dev/null
  if [ -e "$ND_TMP_RUN" ]; then
    echo "ВНИМАНИЕ: не удалось убрать временный каталог $ND_TMP_RUN" >&2
  fi
  return 0
}

trap nd_tmp_cleanup EXIT
