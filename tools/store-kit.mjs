/** Собрать папку одного магазина. */
function собрать({ папка, кадры, сборка, картинка, заголовок, пояснение }) {
  const dir = join(ROOT, папка);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, 'скриншоты'), { recursive: true });
  mkdirSync(join(dir, 'тексты'), { recursive: true });

  const список = кадры
    ? кадры.map(имя => все.find(f => f.startsWith(имя)) ?? имя)
    : все;
  const строки = [];
  список.forEach((файл, i) => {
    if (!existsSync(join(SHOTS, файл))) {
      console.error(`нет кадра ${файл}`);
      process.exitCode = 1;
      return;
    }
    // Нумеруем заново: магазин выкладывает кадры в порядке загрузки
    const имя = `${String(i + 1).padStart(2, '0')}-${файл.replace(/^\d\d-/, '')}`;
    copyFileSync(join(SHOTS, файл), join(dir, 'скриншоты', имя));
    строки.push(`${имя}  ${кб(join(dir, 'скриншоты', имя))}`);
  });

  for (const [имя, текст] of Object.entries(ТЕКСТЫ)) {
    writeFileSync(join(dir, 'тексты', имя), `${текст}\n`, 'utf8');
  }

  if (existsSync(ICON)) copyFileSync(ICON, join(dir, 'значок-512.png'));
  if (картинка && existsSync(FEATURE)) copyFileSync(FEATURE, join(dir, basename(FEATURE)));
  let сборкаИмя = null;
  if (existsSync(сборка)) {
    сборкаИмя = basename(сборка);
    copyFileSync(сборка, join(dir, сборкаИмя));
  } else {
    console.error(`нет сборки ${сборка} — соберите релиз, см. PUBLISHING.md`);
    process.exitCode = 1;
  }

  writeFileSync(join(dir, 'ЧТО-ЗАГРУЖАТЬ.md'),
    `# ${заголовок}\n\n`
    + `Идентификатор приложения: **${ID}**\n`
    + `Версия: **${VERSION}**, versionCode **${CODE}**\n\n`
    + `${пояснение}\n\n`
    + '## Файлы в этой папке\n\n'
    + (сборкаИмя ? `- **${сборкаИмя}** — сама сборка (${мб(join(dir, сборкаИмя))})\n` : '')
    + `- **значок-512.png** — значок приложения, 512×512 (${кб(join(dir, 'значок-512.png'))})\n`
    + (картинка && existsSync(join(dir, basename(FEATURE)))
      ? `- **${basename(FEATURE)}** — графическое изображение карточки, 1024×500 (${кб(join(dir, basename(FEATURE)))})\n`
      : '')
    + `- **скриншоты/** — ${строки.length} шт., 1080×1920, пропорции 9:16\n`
    + `- **тексты/** — название, краткое и полное описание, «что нового»; копируются как есть\n\n`
    + '## Скриншоты по порядку\n\n'
    + строки.map(s => `- ${s}`).join('\n') + '\n\n'
    + 'Порядок здесь — тот, в котором их стоит загрузить: сначала «что это», '
    + 'сразу за ним будильник с задачей (то, чем приложение отличается), потом подробности.\n\n'
    + '## Что заполнить руками\n\n'
    + 'Ответы на все вопросы консоли — категории, возрастной рейтинг, форма о данных, '
    + 'обоснования разрешений — в [STORE-LISTING.md](../../STORE-LISTING.md).\n',
    'utf8');

  console.log(`${папка}: ${строки.length} кадров${сборкаИмя ? `, ${сборкаИмя}` : ''}`);
  return dir;
}

